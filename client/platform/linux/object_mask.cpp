bool WYD_LoadObjectMask(WYDObjectMaskTable& out)
{
	out = {};
	const std::string path = WYD_JoinAssetPath("object.bin");
	std::ifstream in(path, std::ios::binary);
	if (!in)
	{
		out.error = "object.bin ausente: " + path;
		return false;
	}

	constexpr size_t kBytes = static_cast<size_t>(kMaxMask) * kMaskX * kMaskY;
	out.data.resize(kBytes);
	in.read(reinterpret_cast<char*>(out.data.data()), static_cast<std::streamsize>(kBytes));
	if (static_cast<size_t>(in.gcount()) != kBytes)
	{
		out.error = "object.bin truncado";
		return false;
	}

	int nCheckSum = 0;
	for (int mask = 0; mask < kMaxMask; ++mask)
	{
		for (int y = 0; y < kMaskY; ++y)
		{
			for (int x = 0; x < kMaskX; ++x)
			{
				const size_t idx = (static_cast<size_t>(mask) * kMaskY + y) * kMaskX + x;
				const char v = out.data[idx];
				nCheckSum += v % 4 + 2 * y + 5 * mask;
			}
		}
	}

	const int nLen = static_cast<int>(std::strlen(reinterpret_cast<const char*>(kEncKeys)));
	for (size_t j = 0; j < kBytes; ++j)
		out.data[j] = static_cast<int8_t>(
			static_cast<unsigned char>(out.data[j]) - kEncKeys[j % static_cast<size_t>(nLen)] - static_cast<int>(j));

	int nRCheckSum = 0;
	in.read(reinterpret_cast<char*>(&nRCheckSum), 4);
	out.checksum_ok = (nCheckSum == nRCheckSum);
	out.mask_count = kMaxMask;
	if (!out.checksum_ok)
	{
		out.error = "checksum object.bin divergente";
		std::fprintf(stderr, "[WYDLINUX][mask] checksum calc=%d file=%d\n", nCheckSum, nRCheckSum);
		return false;
	}
	std::fprintf(stderr, "[WYDLINUX][mask] object.bin OK masks=%d\n", out.mask_count);
	return true;
}
